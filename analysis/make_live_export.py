#!/usr/bin/env python3
"""
make_live_export.py: the data behind the booth's live dashboard.

Every car in the eight drives of the release's reference scenario
(highway_sparse) gets a verdict from a model that never saw it:

  1. Load the release bundle as baseline_starter does (the 50 release
     features, the purity floor applied).
  2. Split the physical transmitters of every drive into five folds. For each
     fold, train the release baseline (a 60-tree random forest, random_state 0,
     400,000 sampled training rows, as check_release.py and live_demo.py do) on
     the other four folds and predict the held-out one. Every decision on the
     dashboard is therefore out of sample, the way the frozen test split is,
     but covering every car rather than the test cars only.
  3. Aggregate per drive, claimed station and one-second window: how many
     receivers heard it, how many flagged it, the class most of the flagging
     receivers named, and the truth. Also the per-second confusion counts, so
     the page can compute running macro F1 and MCC exactly, and the time one
     model takes to decide a whole second's batch.
  4. Join true and claimed positions every 200 ms from the simulator's
     transmit log (campaign_gnss/tx_seed*.csv, the same drives: the station
     sets and attack labels are checked to agree), and the roadside units.

Writes web/data/drive<N>.js (one per drive) and web/data/live_meta.js.
One heavy job: about ten minutes and a few GB of memory.

    /usr/bin/python3 analysis/make_live_export.py [--bundle ~/ns3-v2x/runs/release]
"""
import argparse
import json
import pathlib
import sys
import time

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import f1_score, matthews_corrcoef

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from baseline_starter import load  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parent.parent
RUNS = pathlib.Path.home() / "ns3-v2x" / "runs"
CAMPAIGN = RUNS / "campaign_gnss"
OUT = REPO / "web" / "data"
CLASSES = [0, 1, 3, 4, 5, 6, 7, 8, 11, 12, 13]
FRAME_MS = 200


def js(name, key, sub, data):
    blob = json.dumps(data, separators=(",", ":"), allow_nan=False)
    target = f"window.SITE.{key}" + (f"[{sub}]" if sub is not None else "")
    pre = "window.SITE=window.SITE||{};" + (f"window.SITE.{key}=window.SITE.{key}||{{}};" if sub is not None else "")
    (OUT / f"{name}.js").write_text(
        "/* generated by analysis/make_live_export.py; do not edit */\n" + pre + f"{target}={blob};\n")
    print(f"  {name}.js {len(blob) / 1024:8.1f} KB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", default=str(RUNS / "release"))
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--trees", type=int, default=60)
    ap.add_argument("--sample", type=int, default=400000)
    ap.add_argument("--jobs", type=int, default=3)
    a = ap.parse_args()

    schema = json.loads((pathlib.Path(a.bundle) / "schema.json").read_text())
    feats = [c["name"] for c in schema["columns"] if c["is_feature"]]
    df = load(a.bundle, "highway_sparse")
    df = df[["key_seed", "key_claimedStationId", "key_window", "key_rxNodeId",
             "label_attackId", "label_txNodeId"] + feats].reset_index(drop=True)
    X = df[feats].astype("float32").fillna(-999).to_numpy()
    y = df.label_attackId.to_numpy()
    print(f"{len(df):,} receiver windows, {df.key_seed.nunique()} drives, {len(feats)} features")

    # folds of physical transmitters, drawn per drive
    tx = (df.key_seed + ":" + df.label_txNodeId.astype(str)).to_numpy()
    uniq = np.unique(tx)
    rng = np.random.default_rng(0)
    fold_of = dict(zip(uniq, rng.permutation(len(uniq)) % a.folds))
    fold = np.array([fold_of[t] for t in tx])
    pred = np.full(len(df), -1, dtype=np.int16)
    first = None
    for k in range(a.folds):
        tr = np.flatnonzero(fold != k)
        if len(tr) > a.sample:
            tr = np.sort(np.random.default_rng(k).choice(tr, a.sample, replace=False))
        t0 = time.time()
        clf = RandomForestClassifier(n_estimators=a.trees, n_jobs=a.jobs, random_state=0)
        clf.fit(X[tr], y[tr])
        te = np.flatnonzero(fold == k)
        pred[te] = clf.predict(X[te])
        print(f"  fold {k + 1}/{a.folds}: trained on {len(tr):,}, predicted {len(te):,} held-out windows "
              f"in {time.time() - t0:.0f} s", flush=True)
        if first is None:
            first = clf
        else:
            del clf
    if (pred < 0).any():
        sys.exit("FAILED: some windows were never predicted")
    df["pred"] = pred
    f1 = f1_score(y, pred, average="macro")
    mcc = matthews_corrcoef(y, pred)
    print(f"out of fold over every car: macro F1 {f1:.4f}, MCC {mcc:.4f}")

    # time one model deciding each second's batch, as a deployed receiver would
    timing = {}
    for (seed, win), idx in df.groupby(["key_seed", "key_window"]).indices.items():
        t0 = time.perf_counter()
        first.predict(X[idx])
        timing[(seed, int(win))] = (time.perf_counter() - t0) * 1e6 / len(idx)
    del X

    # how the alert threshold behaves, to choose and to state it
    g = df.assign(flag=(df.pred != 0)).groupby(["key_seed", "key_claimedStationId", "key_window"])
    st = g.agg(n=("flag", "size"), k=("flag", "sum"), truth=("label_attackId", "first")).reset_index()
    for share in (0.25, 0.5):
        al = st.k >= np.ceil(share * st.n)
        hon, att = st.truth == 0, st.truth != 0
        print(f"  alert when at least {share:.0%} of receivers flag: honest station seconds alerted "
              f"{al[hon].mean():.4f}, attacker station seconds alerted {al[att].mean():.4f}")

    OUT.mkdir(parents=True, exist_ok=True)
    rsu_all = None
    meta = {"src": ["analysis/make_live_export.py", "release highway_sparse", "runs/campaign_gnss/tx_seed*.csv"],
            "classes": CLASSES, "frame_ms": FRAME_MS, "folds": a.folds, "trees": a.trees,
            "f1_all": round(float(f1), 4), "mcc_all": round(float(mcc), 4), "drives": []}
    for d, seed in enumerate(sorted(df.key_seed.unique(), key=lambda s: int(s[4:])), 1):
        sd = df[df.key_seed == seed]
        txl = pd.read_csv(CAMPAIGN / f"tx_{seed}.csv",
                          usecols=["txTimeMs", "txNodeId", "claimedStationId", "trueX", "trueY",
                                   "claimedX", "claimedY", "attackId"], on_bad_lines="skip").dropna()
        lab = sd.groupby("key_claimedStationId").label_attackId.first()
        txa = txl.groupby("claimedStationId").attackId.agg(lambda s: int(s.mode().iloc[0]))
        if set(lab.index) - set(txa.index) or (lab != txa.reindex(lab.index)).any():
            sys.exit(f"FAILED: {seed} stations or labels differ between the bundle and the transmit log")
        txl["frame"] = (txl.txTimeMs // FRAME_MS).astype(int)
        txl = txl.sort_values("txTimeMs").groupby(["claimedStationId", "frame"]).last().reset_index()
        f0, f1_ = int(txl.frame.min()), int(txl.frame.max())
        stations = []
        for sid, gg in txl.groupby("claimedStationId"):
            gg = gg.set_index("frame").reindex(range(f0, f1_ + 1))
            cols = [gg[c].round(1).mul(10).fillna(-99999).astype(int).tolist()
                    for c in ("trueX", "trueY", "claimedX", "claimedY")]
            stations.append({"id": int(sid), "attack": int(txa[sid]),
                             "tx": int(gg.txNodeId.dropna().mode().iloc[0]),
                             "pos": [v for quad in zip(*cols) for v in quad]})
        # per station-second verdicts
        sec = []
        for (sid, win), gg in sd.groupby(["key_claimedStationId", "key_window"]):
            p = gg.pred.to_numpy()
            flagged = p[p != 0]
            top = int(pd.Series(flagged).mode().iloc[0]) if len(flagged) else 0
            sec.append([int(win), int(sid), int(len(p)), int(len(flagged)), top, int(gg.label_attackId.iloc[0])])
        # per-second confusion counts over every receiver decision
        conf = {}
        for win, gg in sd.groupby("key_window"):
            cc = gg.groupby(["label_attackId", "pred"]).size()
            conf[int(win)] = [[CLASSES.index(int(t)), CLASSES.index(int(p_)), int(n)] for (t, p_), n in cc.items()]
        us = {int(w): round(v, 1) for (s_, w), v in timing.items() if s_ == seed}
        # roadside units: receivers that never move
        rx = pd.read_csv(CAMPAIGN / f"rx_app_{seed}.csv", nrows=400000,
                         usecols=["rxNodeId", "rxX", "rxY", "rxSpeed"], on_bad_lines="skip")
        rx = rx.groupby("rxNodeId").agg(x=("rxX", "median"), y=("rxY", "median"), v=("rxSpeed", "max"))
        rsu = sorted([[round(float(r.x)), round(float(r.y))] for r in rx[rx.v == 0].itertuples()])
        rsu_all = rsu_all or rsu
        js(f"drive{d}", "drives", d, {
            "seed": seed, "f0": f0, "f1": f1_, "stations": stations, "seconds": sec,
            "conf": conf, "us": us, "rsu": rsu,
            "decisions": int(len(sd)),
        })
        meta["drives"].append({"n": d, "seed": seed, "f0": f0, "f1": f1_, "stations": len(stations),
                               "decisions": int(len(sd))})
    meta["road_m"] = float((CAMPAIGN / "road_length_m").read_text().split()[0])
    js("live_meta", "live_meta", None, meta)
    print("EXPORT DONE")


if __name__ == "__main__":
    main()
